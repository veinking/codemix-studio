import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const shareDialog = readFileSync(new URL('../src/components/ShareDialog.tsx', import.meta.url), 'utf8');
const sharedCode = readFileSync(new URL('../src/pages/SharedCode.tsx', import.meta.url), 'utf8');
const ide = readFileSync(new URL('../src/pages/IDE.tsx', import.meta.url), 'utf8');
const migration = readFileSync(new URL('../supabase/migrations/20260825144000_harden_bide_shared_code.sql', import.meta.url), 'utf8');
const cleanupMigration = readFileSync(new URL('../supabase/migrations/20260825144600_remove_shared_code_update_policy.sql', import.meta.url), 'utf8');
const tableAccessMigration = readFileSync(new URL('../supabase/migrations/20260825144900_revoke_shared_code_client_table_access.sql', import.meta.url), 'utf8');

// Share creation must be authenticated and mediated by the validated server RPC.
assert.match(shareDialog, /useAuth\(\)/, 'Share dialog must know whether the user is signed in');
assert.match(shareDialog, /create_shared_code/, 'Share creation must use the hardened RPC');
assert.match(shareDialog, /Sign in to share/, 'Guests must be directed to sign in before creating shares');
assert.doesNotMatch(shareDialog, /\.from\(["']shared_code["']\)/, 'Client must not insert directly into shared_code');
assert.doesNotMatch(shareDialog, /generateShortId/, 'Share IDs must be generated by the server');

// Public viewing must fetch one secret token through RPC, never list the backing table.
assert.match(sharedCode, /get_shared_code/, 'Shared code page must use exact-token fetch RPC');
assert.doesNotMatch(sharedCode, /\.from\(["']shared_code["']\)/, 'Shared code page must not query the backing table directly');
assert.doesNotMatch(sharedCode, /Thank you for reporting/, 'UI must not claim reports are stored when there is no reporting backend');

// Forking should be a real same-origin editor handoff without putting source in the URL.
assert.match(sharedCode, /bide_shared_fork_code/, 'Shared page must place fork source in a one-time session handoff');
assert.match(ide, /bide_shared_fork_code/, 'IDE must consume the one-time shared-code handoff');
assert.match(ide, /Shared code loaded into the editor/, 'IDE must visibly confirm the fork handoff');

// Database contract: the backing table is inaccessible to browser roles;
// authenticated creation and exact-token public fetch happen only through RPCs.
assert.match(migration, /REVOKE ALL ON TABLE public\.shared_code FROM anon;/, 'Anonymous clients must not access shared_code directly');
assert.match(tableAccessMigration, /REVOKE ALL ON TABLE public\.shared_code FROM anon;/, 'Final migration must keep anonymous table access revoked');
assert.match(tableAccessMigration, /REVOKE ALL ON TABLE public\.shared_code FROM authenticated;/, 'Final migration must remove direct authenticated table access too');
assert.match(migration, /CREATE OR REPLACE FUNCTION public\.create_shared_code/, 'Create-share RPC must exist');
assert.match(migration, /CREATE OR REPLACE FUNCTION public\.get_shared_code/, 'Get-share RPC must exist');
assert.match(migration, /SECURITY DEFINER[\s\S]*?SET search_path = ''/, 'Share RPCs must pin an empty search_path');
assert.match(migration, /gen_random_bytes\(12\)/, 'Share identifiers must carry 96 bits of server-generated entropy');
assert.match(migration, /p_short_id !~ '\^\[0-9a-f\]\{24\}\$'/, 'Public fetch must require the full secret-token format');
assert.match(migration, /GRANT EXECUTE ON FUNCTION public\.create_shared_code[\s\S]*?TO authenticated;/, 'Only authenticated users may call create-share RPC');
assert.match(migration, /GRANT EXECUTE ON FUNCTION public\.get_shared_code[\s\S]*?TO anon, authenticated;/, 'Anonymous viewers may call only the exact-token fetch RPC');
assert.match(cleanupMigration, /DROP POLICY IF EXISTS shared_code_update_own/, 'Obsolete direct share-update policy must remain removed');

console.log('✓ Shared-code security + fork workflow regression guard passed');
